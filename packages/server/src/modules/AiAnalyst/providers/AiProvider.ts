/**
 * Интерфейс модели (этап 13 ТЗ, §13.2).
 *
 * Провайдер вынесен за интерфейс не ради красоты. Продукт метит в реестр
 * российского ПО и разворачивается на своих серверах: у одного покупателя
 * это YandexGPT, у другого — GigaChat, у третьего — своя модель внутри
 * контура, а у четвёртого ИИ не нужен вовсе. Зашей любой из них в код — и
 * остальным трём продукт не подходит.
 */

/** Что умеет провайдер. */
export interface AiProvider {
  /** Ключ провайдера: `yandex_gpt`, `gigachat`, `openai_compatible`, `off`. */
  readonly key: string;

  /**
   * Работает ли модель ВНУТРИ контура организации.
   *
   * От этого зависит, доступен ли раздел при запрете передавать данные во
   * внешние сервисы (§13.1 п. 5).
   */
  readonly isLocal: boolean;

  /** Настроен ли провайдер: есть ключ, адрес и всё, что ему нужно. */
  isConfigured(): boolean;

  /**
   * Спрашивает модель.
   *
   * На вход идёт УЖЕ ПРОВЕРЕННЫЙ промпт: чистка приватных полей — не дело
   * провайдера, иначе её пришлось бы повторять в каждой реализации, и
   * однажды кто-нибудь забыл бы.
   */
  complete(prompt: string, options?: AiCompleteOptions): Promise<string>;
}

export interface AiCompleteOptions {
  /** Потолок длины ответа: наблюдения короткие, платить за роман незачем. */
  maxTokens?: number;
  /**
   * Насколько модели позволено «фантазировать». Для выводов по цифрам берём
   * низкое значение: нам нужна формулировка, а не творчество.
   */
  temperature?: number;
  /** Сколько ждать ответа. Фоновая задача не должна висеть вечно. */
  timeoutMs?: number;
}

export interface AiProviderSettings {
  provider?: string | null;
  apiKey?: string | null;
  /** Адрес для OpenAI-совместимой модели — в том числе своей, локальной. */
  endpoint?: string | null;
  /** Идентификатор каталога/проекта: нужен YandexGPT. */
  folderId?: string | null;
  model?: string | null;
}

/** Ключ провайдера «выключено». */
export const AI_PROVIDER_OFF = 'off';
