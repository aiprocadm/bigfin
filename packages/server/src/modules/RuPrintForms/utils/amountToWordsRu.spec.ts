import {
  amountToWordsRu,
  formatDateRu,
  formatMoneyRu,
  integerToWordsRu,
  pluralizeRu,
} from './amountToWordsRu';

describe('pluralizeRu', () => {
  const forms: [string, string, string] = ['рубль', 'рубля', 'рублей'];

  it.each([
    [1, 'рубль'],
    [2, 'рубля'],
    [4, 'рубля'],
    [5, 'рублей'],
    [0, 'рублей'],
    [11, 'рублей'],
    [12, 'рублей'],
    [14, 'рублей'],
    [21, 'рубль'],
    [22, 'рубля'],
    [25, 'рублей'],
    [111, 'рублей'],
    [121, 'рубль'],
  ])('%i → %s', (count, expected) => {
    expect(pluralizeRu(count as number, forms)).toBe(expected);
  });
});

describe('integerToWordsRu', () => {
  it.each([
    [0, 'ноль'],
    [1, 'один'],
    [2, 'два'],
    [7, 'семь'],
    [10, 'десять'],
    [11, 'одиннадцать'],
    [14, 'четырнадцать'],
    [19, 'девятнадцать'],
    [20, 'двадцать'],
    [21, 'двадцать один'],
    [40, 'сорок'],
    [99, 'девяносто девять'],
    [100, 'сто'],
    [101, 'сто один'],
    [111, 'сто одиннадцать'],
    [345, 'триста сорок пять'],
    [1000, 'одна тысяча'],
    [1001, 'одна тысяча один'],
    [2000, 'две тысячи'],
    [5000, 'пять тысяч'],
    [21000, 'двадцать одна тысяча'],
    [1500, 'одна тысяча пятьсот'],
    [100000, 'сто тысяч'],
    [1000000, 'один миллион'],
    [2000000, 'два миллиона'],
    [5000000, 'пять миллионов'],
    [1000000000, 'один миллиард'],
    [2000001002, 'два миллиарда одна тысяча два'],
  ])('%i → «%s»', (value, expected) => {
    expect(integerToWordsRu(value as number)).toBe(expected);
  });

  it('пропускает нулевые тройки («один миллион пять» — без тысяч)', () => {
    expect(integerToWordsRu(1000005)).toBe('один миллион пять');
  });

  it('бросает ошибку на отрицательных', () => {
    expect(() => integerToWordsRu(-1)).toThrow();
  });

  it('бросает ошибку от триллиона и выше', () => {
    expect(() => integerToWordsRu(1_000_000_000_000)).toThrow();
  });
});

describe('amountToWordsRu', () => {
  it.each([
    [0, 'Ноль рублей 00 копеек'],
    [1, 'Один рубль 00 копеек'],
    [2, 'Два рубля 00 копеек'],
    [1500, 'Одна тысяча пятьсот рублей 00 копеек'],
    [1500.05, 'Одна тысяча пятьсот рублей 05 копеек'],
    [1500.5, 'Одна тысяча пятьсот рублей 50 копеек'],
    [21.01, 'Двадцать один рубль 01 копейка'],
    [3.02, 'Три рубля 02 копейки'],
    [1234567.89, 'Один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь рублей 89 копеек'],
  ])('%f → «%s»', (amount, expected) => {
    expect(amountToWordsRu(amount as number)).toBe(expected);
  });

  it('округляет до копеек (0.005 → 01 копейка)', () => {
    expect(amountToWordsRu(0.005)).toBe('Ноль рублей 01 копейка');
  });

  it('99.999 округляется до 100 рублей ровно', () => {
    expect(amountToWordsRu(99.999)).toBe('Сто рублей 00 копеек');
  });

  it('бросает ошибку на отрицательной сумме', () => {
    expect(() => amountToWordsRu(-1)).toThrow();
  });

  it('бросает ошибку на NaN/Infinity', () => {
    expect(() => amountToWordsRu(NaN)).toThrow();
    expect(() => amountToWordsRu(Infinity)).toThrow();
  });
});

describe('formatMoneyRu', () => {
  it.each([
    [0, '0,00'],
    [1, '1,00'],
    [1500, '1 500,00'],
    [1500.5, '1 500,50'],
    [1234567.89, '1 234 567,89'],
    [-99.9, '-99,90'],
    [0.005, '0,01'],
  ])('%f → «%s»', (amount, expected) => {
    expect(formatMoneyRu(amount as number)).toBe(expected);
  });
});

describe('formatDateRu', () => {
  it('форматирует дату родительным падежом', () => {
    expect(formatDateRu(new Date(2026, 6, 26))).toBe('26 июля 2026 г.');
    expect(formatDateRu(new Date(2026, 0, 1))).toBe('1 января 2026 г.');
  });

  it('невалидная дата → пустая строка', () => {
    expect(formatDateRu('not-a-date')).toBe('');
  });
});
