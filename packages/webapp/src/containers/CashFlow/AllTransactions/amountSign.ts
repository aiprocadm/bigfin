/**
 * Сумма строки реестра со знаком (UI-042-8 ТЗ-4).
 *
 * Приход и расход по 500 000 различались только цветом: расход у нас
 * намеренно не красный, а цвет не видят дальтоники и не видно на печати.
 * Знак говорит направление денег сам: «+500 000,00» и «−500 000,00».
 *
 * Минус — типографский (U+2212): той же ширины, что плюс, столбец сумм
 * не «пляшет».
 */
export const MINUS = '−';

export function signedAmount(
  formatted: string | null | undefined,
  isDeposit: boolean,
): string {
  const text = (formatted ?? '').trim();
  // Пусто, прочерк или знак уже стоит — не трогаем.
  if (!text || text === '—' || /^[+\-−]/.test(text)) return text || '—';
  return `${isDeposit ? '+' : MINUS}${text}`;
}
