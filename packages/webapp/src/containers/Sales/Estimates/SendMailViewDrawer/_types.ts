export interface SendMailViewFormValues {
  /**
   * Отправитель. Необязателен: его подставляет сервер из настроек организации,
   * и только окно «оплата получена» задаёт его вручную. Прежняя запись
   * требовала его от всех — и четыре окна отправки письма считались ошибкой
   * (Д11 карты v75).
   */
  from?: Array<string>;
  to: Array<string>;
  cc: Array<string>;
  bcc: Array<string>;
  subject: string;
  message: string;
  /**
   * Приложить документ отдельным файлом. Настоящее поле формы — галочку рисуют
   * все пять окон отправки, но в общем объявлении его не было.
   */
  attachPdf?: boolean;
}
