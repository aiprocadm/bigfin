/**
 * Приводит значение настройки к «да/нет».
 *
 * Зачем это нужно. Настройки хранятся в базе СТРОКАМИ. Переключатель, который
 * когда-то включали, а потом выключили, возвращается строкой «0» — и любая
 * проверка вида `if (!value)` пропускает его как включённый, потому что
 * непустая строка в JavaScript истинна.
 *
 * Дефект прячется идеально: настройка, которой ни разу не пользовались,
 * отдаёт настоящее `false` из умолчаний и ведёт себя правильно. Ломаются
 * ровно те, что переключали руками, — то есть самый обычный сценарий.
 *
 * Найдено дважды: на модулях за флагом и на блокировке периода.
 */
export const toBoolean = (value: unknown): boolean => {
  if (typeof value === 'string') {
    const normalized = value.trim().toLowerCase();
    if (normalized === '' || normalized === '0' || normalized === 'false') {
      return false;
    }
    return true;
  }
  return Boolean(value);
};
