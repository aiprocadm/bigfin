import type { QueryClient } from 'react-query';

/**
 * Общие типы хуков запросов.
 *
 * ЗАЧЕМ. Каждый хук запроса устроен одинаково: принимает необязательные
 * настройки и передаёт их дальше в react-query, а помощники сброса кеша
 * получают клиента запросов. Ни то, ни другое нигде не было объявлено — и
 * из этого складывалась заметная часть слепой зоны витрины.
 *
 * `any` здесь был бы бесполезен вдвойне: замечание исчезло бы, а незнание
 * осталось. Названные типы говорят, ЧТО это за значение, даже когда его
 * внутреннее устройство нам не важно.
 */

/**
 * Дополнительные настройки хука — уходят в react-query как есть.
 *
 * Набор у каждого вызова свой (`enabled`, `onSuccess`, `select`, …),
 * поэтому здесь описано главное: это ОБЪЕКТ настроек, а не что попало.
 */
export type QueryHookOptions = Record<string, any>;

/** Клиент запросов: через него сбрасывают кеш после правок. */
export type QueryCacheClient = QueryClient;
