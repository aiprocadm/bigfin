import { describe, expect, it } from 'vitest';

import { isGoodChange } from './overviewChangeTone';

/**
 * Хорошая ли новость это изменение показателя.
 *
 * Раньше рост красился зелёным ВСЕГДА: рост расходов на 20% выглядел хорошей
 * новостью, а их снижение — плохой. Ошибка незаметная: цвет не врёт грубо, он
 * просто хвалит не за то.
 */
describe('isGoodChange', () => {
  it('рост доходов — хорошо', () => {
    expect(isGoodChange('income', 20)).toBe(true);
  });

  it('падение доходов — не хорошо', () => {
    expect(isGoodChange('income', -20)).toBe(false);
  });

  it('РОСТ РАСХОДОВ — НЕ ХОРОШО', () => {
    // Красить его зелёным значит поздравлять человека с тем, что он стал
    // больше тратить.
    expect(isGoodChange('expense', 20)).toBe(false);
  });

  it('снижение расходов — хорошо', () => {
    expect(isGoodChange('expense', -20)).toBe(true);
  });

  it('НОЛЬ НЕ КРАСИТСЯ: ничего не изменилось — нечего и хвалить', () => {
    // Найдено живым проходом: под убытком в 20 000 ₽ стояла ЗЕЛЁНАЯ подпись
    // «+0 %». Ноль — это не хорошая новость, а отсутствие новости. Тот же род
    // ошибки, что «рост расходов зелёным», который чинили раньше.
    expect(isGoodChange('income', 0)).toBe(false);
    expect(isGoodChange('expense', 0)).toBe(false);
    expect(isGoodChange(undefined, 0)).toBe(false);
  });

  it('без вида показателя рост считается хорошим', () => {
    // Прибыль и остаток идут без пометки: у них рост и правда хорош.
    expect(isGoodChange(undefined, 5)).toBe(true);
    expect(isGoodChange(undefined, -5)).toBe(false);
  });

  it('ноль — не падение, но и не повод красить зелёным', () => {
    /*
      РЕШЕНИЕ ПЕРЕСМОТРЕНО ПОСЛЕ ЖИВОГО ПРОХОДА.

      Здесь стояло `toBe(true)` с доводом «столько же, сколько в прошлом
      месяце, — это не плохая новость». Довод верен, а вывод из него — нет.

      Ответ у этой проверки ровно один потребитель: он выбирает между ЗЕЛЁНЫМ
      и обычными чернилами. «Не плохо» — это чернила, а не похвала. Считая
      ноль хорошим, продукт хвалил за то, что ничего не произошло.

      Живое доказательство: на главной под убытком в 20 000 ₽ стояла зелёная
      подпись «+0 %».

      Заметно и то, что прежнее правило было несимметричным: ноль у доходов
      красился зелёным, а ноль у расходов — нет (проверка ниже). Одно и то же
      «ничего не изменилось» получало два разных ответа.
    */
    expect(isGoodChange('income', 0)).toBe(false);
    expect(isGoodChange(undefined, 0)).toBe(false);
  });

  it('нулевой рост расходов — тоже не плохая новость', () => {
    // Но и не хорошая: расходы не снизились. Зелёным не отмечаем.
    expect(isGoodChange('expense', 0)).toBe(false);
  });
});
