import { useLocation } from 'react-router-dom';

/**
 * Состояние, переданное вместе с переходом.
 *
 * Экраны заводят запись «из другой»: из счёта — кредит-нота, из товара — его
 * копия. Что именно передано, кладут в состояние перехода
 * (`history.push(путь, { action: id })`).
 *
 * Зачем отдельный крючок: у `useLocation()` состояние объявлено пустым
 * объектом, поэтому `state?.action` считается обращением к несуществующему
 * свойству, и **каждый** такой поставщик оставался под пометкой
 * «не проверять типы» (Д8 карты v82). Здесь вид называется один раз в месте
 * чтения.
 *
 * Возвращается пустой объект, если состояния нет вовсе, — читать через `?.`
 * больше не нужно, но и не вредно.
 */
export const useRouteState = <S extends object>(): Partial<S> =>
  (useLocation<S | undefined>().state ?? {}) as Partial<S>;

/** Обычное «завести копией/из другой записи»: идёт под ключом `action`. */
export interface RouteActionState {
  action?: number;
}
