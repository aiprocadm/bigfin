import { extractContacts, extractItems } from './extractCommerceMl';
import { parseXml } from './parseXml';

const IMPORT_XML = `<?xml version="1.0" encoding="UTF-8"?>
<КоммерческаяИнформация ВерсияСхемы="2.05" ДатаФормирования="2026-07-30">
  <Классификатор>
    <Ид>cls-1</Ид>
    <Наименование>Каталог товаров</Наименование>
  </Классификатор>
  <Каталог СодержитТолькоИзменения="true">
    <Ид>cat-1</Ид>
    <Товары>
      <Товар>
        <Ид>item-1</Ид>
        <Артикул>ART-001</Артикул>
        <Наименование>Стул офисный</Наименование>
        <БазоваяЕдиница Код="796">шт</БазоваяЕдиница>
        <Описание>Ткань, чёрный</Описание>
      </Товар>
      <Товар>
        <Ид>item-2</Ид>
        <Наименование>Услуга доставки</Наименование>
      </Товар>
      <Товар>
        <Ид>item-3</Ид>
        <Наименование>Снятый с продажи</Наименование>
        <ПометкаУдаления>true</ПометкаУдаления>
      </Товар>
      <Товар>
        <Наименование>Без идентификатора</Наименование>
      </Товар>
    </Товары>
  </Каталог>
</КоммерческаяИнформация>`;

const CONTRAGENTS_XML = `<?xml version="1.0" encoding="UTF-8"?>
<КоммерческаяИнформация ВерсияСхемы="2.05">
  <Контрагенты>
    <Контрагент>
      <Ид>c-1</Ид>
      <Наименование>ООО Ромашка</Наименование>
      <ОфициальноеНаименование>Общество с ограниченной ответственностью «Ромашка»</ОфициальноеНаименование>
      <ИНН>7707083893</ИНН>
      <КПП>770701001</КПП>
    </Контрагент>
    <Контрагент>
      <Ид>c-2</Ид>
      <Наименование>ИП Иванов</Наименование>
    </Контрагент>
  </Контрагенты>
</КоммерческаяИнформация>`;

describe('extractItems', () => {
  it('достаёт товары с артикулом, единицей и описанием', () => {
    const items = extractItems(parseXml(IMPORT_XML));

    expect(items).toHaveLength(2);
    expect(items[0]).toEqual({
      externalId: 'item-1',
      name: 'Стул офисный',
      sku: 'ART-001',
      unit: 'шт',
      description: 'Ткань, чёрный',
    });
    expect(items[1]).toEqual({
      externalId: 'item-2',
      name: 'Услуга доставки',
      sku: null,
      unit: null,
      description: null,
    });
  });

  it('пропускает помеченные на удаление и записи без Ид/Наименования', () => {
    const items = extractItems(parseXml(IMPORT_XML));

    expect(items.map((i) => i.externalId)).not.toContain('item-3');
    expect(items.every((i) => i.externalId && i.name)).toBe(true);
  });

  it('на файле без каталога возвращает пустой список, а не падает', () => {
    expect(extractItems(parseXml('<КоммерческаяИнформация/>'))).toEqual([]);
  });
});

describe('extractContacts', () => {
  it('достаёт контрагентов с ИНН/КПП и полным наименованием', () => {
    const contacts = extractContacts(parseXml(CONTRAGENTS_XML));

    expect(contacts).toHaveLength(2);
    expect(contacts[0]).toEqual({
      externalId: 'c-1',
      name: 'ООО Ромашка',
      fullName: 'Общество с ограниченной ответственностью «Ромашка»',
      inn: '7707083893',
      kpp: '770701001',
    });
    expect(contacts[1].inn).toBeNull();
  });

  it('находит контрагентов и внутри Классификатора', () => {
    const xml = `<КоммерческаяИнформация><Классификатор><Контрагенты>
      <Контрагент><Ид>k-1</Ид><Наименование>ООО Тест</Наименование></Контрагент>
    </Контрагенты></Классификатор></КоммерческаяИнформация>`;

    expect(extractContacts(parseXml(xml)).map((c) => c.externalId)).toEqual([
      'k-1',
    ]);
  });

  it('на файле без контрагентов возвращает пустой список', () => {
    expect(extractContacts(parseXml(IMPORT_XML))).toEqual([]);
  });
});
