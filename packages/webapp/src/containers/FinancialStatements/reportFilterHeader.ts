/**
 * Общий вид шапки отчёта с отбором.
 *
 * Четыре шапки — обороты покупателей, обороты поставщиков, движение товара,
 * сводка по НДС — устроены ОДИНАКОВО: принимают текущий отбор, отдают новый
 * и умеют закрыть шторку. Ни у одной из них вид не был объявлен.
 *
 * Общий тип, а не четыре одинаковых: четыре копии одного описания рано или
 * поздно расходятся, и расхождение находится не сразу, а через полгода на
 * пятой шапке.
 */

/** Помощники Formik, которые приходят вторым доводом в отправку формы. */
export interface FormikSubmitHelpers {
  setSubmitting: (isSubmitting: boolean) => void;
}

/**
 * Свойства шапки отчёта с отбором.
 *
 * Отбор намеренно описан свободно (`Record`): у каждого отчёта свой набор
 * полей, и перечислять их здесь значило бы завести общее описание, которое
 * не подходит никому.
 */
export interface ReportFilterHeaderProps<
  TFilter extends Record<string, any> = Record<string, any>,
> {
  /** Применить новый отбор. */
  onSubmitFilter: (values: TFilter) => void;
  /** Отбор, который действует сейчас. */
  pageFilter: TFilter;
  /** Открыта ли шторка отбора. */
  isFilterDrawerOpen?: boolean;
}
