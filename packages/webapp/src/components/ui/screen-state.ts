/**
 * Четыре обязательных состояния экрана (этап 5 ТЗ, §5.3).
 *
 * | Состояние | Что показываем |
 * |---|---|
 * | Загрузка | скелетон в форме будущего содержимого, не спиннер по центру |
 * | Ошибка | что случилось человеческим языком + кнопка «Повторить» |
 * | Пусто | объяснение раздела + кнопка первого действия |
 * | Данные | собственно экран |
 *
 * Порядок выбора здесь — не мелочь, поэтому он вынесен в отдельное правило
 * и проверяется сам по себе.
 */

export type ScreenState = 'loading' | 'error' | 'empty' | 'data';

export interface ScreenStateInput {
  isLoading?: boolean;
  isError?: boolean;
  isEmpty?: boolean;
}

/**
 * Какое состояние показать.
 *
 * **Загрузка важнее ошибки.** Пока идёт повторный запрос, показывать старую
 * ошибку — значит утверждать, что всё по-прежнему сломано, хотя мы как раз
 * проверяем обратное. Человек жмёт «Повторить» и не понимает, сработало ли.
 *
 * **Ошибка важнее пустоты.** Пустой экран говорит «здесь ничего нет» — это
 * утверждение о данных. При ошибке мы про данные ничего не знаем, и сказать
 * «ничего нет» значит соврать: человек решит, что у него нет операций, и
 * пойдёт их заводить заново.
 */
export function pickScreenState(input: ScreenStateInput): ScreenState {
  if (input.isLoading) return 'loading';
  if (input.isError) return 'error';
  if (input.isEmpty) return 'empty';
  return 'data';
}
