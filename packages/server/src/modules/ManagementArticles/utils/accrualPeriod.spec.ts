import { profitDateOf } from './accrualPeriod';

/**
 * Месяц начисления в отчётах о прибыли (FT-013 ТЗ-3).
 *
 * Критерий приёмки 1: операция от 05.01.2026 с месяцем начисления 2025-12
 * попадает в ОПиУ за декабрь (а в ОДДС — за январь: отчёт о деньгах этим
 * правилом не пользуется вовсе).
 */
describe('дата операции в отчёте о прибыли', () => {
  it('критерий 1: платёж 05.01.2026 с начислением 2025-12 — в декабре', () => {
    expect(profitDateOf({ date: new Date(2026, 0, 5), accrualPeriod: '2025-12' })).toBe(
      '2025-12-01',
    );
  });

  it('без месяца начисления — своя дата', () => {
    expect(profitDateOf({ date: new Date(2026, 0, 5), accrualPeriod: null })).toBe('2026-01-05');
    expect(profitDateOf({ date: '2026-01-05 00:00:00' })).toBe('2026-01-05');
  });

  it('отчёт с середины месяца начисления — операция не выпадает за левый край', () => {
    expect(profitDateOf({ date: '2026-02-03', accrualPeriod: '2026-01' }, '2026-01-15')).toBe(
      '2026-01-15',
    );
    // Другой месяц — первое число, как обычно.
    expect(profitDateOf({ date: '2026-02-03', accrualPeriod: '2025-12' }, '2026-01-15')).toBe(
      '2025-12-01',
    );
  });
});
