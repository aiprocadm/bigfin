/**
 * Какой курс подставить в форму документа после ответа службы курсов.
 *
 * Раньше здесь стояло «полученный курс ИЛИ единица»: когда служба не
 * отвечала (а она, как показала живая проба, не отвечала всегда), в счёт в
 * иностранной валюте молча уезжал курс 1 — доллар считался равным рублю.
 * Теперь «не знаем» возвращает `null`, и форма оставляет поле человеку.
 *
 * М3 срез 2 карты v15.
 */
export function pickSyncedExRate(fetched: unknown): number | null {
  const rate = Number(fetched);

  return Number.isFinite(rate) && rate > 0 ? rate : null;
}
