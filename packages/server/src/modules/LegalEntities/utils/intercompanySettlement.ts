/**
 * Расчёты внутри группы (остаток К9).
 *
 * ЧТО ЛОМАЛОСЬ. Перевод 500 000 между двумя своими юрлицами кладёт одну ногу
 * на счёт ООО, другую — на счёт ИП. Сводный баланс сходится: обе ноги внутри
 * отчёта. Баланс ОДНОГО юрлица не сходится ровно на сумму перевода: видна
 * только его нога. Деньги ушли, а требования к своему же юрлицу в балансе нет.
 *
 * ЧЕМ ЛЕЧИМ. Тем же, чем лечит это настоящий бухгалтер: встречным требованием.
 * Отдал — тебе должны, получил — должен ты. Только требование не записывается
 * в базу отдельными проводками, а СЧИТАЕТСЯ из тех же самых проводок.
 *
 * ПОЧЕМУ СЧИТАЕТСЯ, А НЕ ПИШЕТСЯ. Записать пару новых проводок значит: завести
 * два счёта, накатить миграцию на все организации и ПЕРЕПРОВЕСТИ всю историю —
 * иначе у старых переводов встречного требования не появится, и баланс за
 * прошлый год так и не сойдётся. Вычисление работает на всей истории сразу и
 * не может разойтись с проводками: оно из них и получено.
 *
 * ГЛАВНОЕ СВОЙСТВО. Величина требования равна перекосу отчёта, взятому с
 * обратным знаком. Двойная запись означает, что по ВСЕМ проводкам дебет равен
 * кредиту. Значит перекос отбора — это ровно то, что у отбора отняли: ноги,
 * ушедшие к другим юрлицам. Поэтому строку не надо угадывать — её достаточно
 * измерить.
 */

/**
 * Номер вычисляемого счёта «Расчёты внутри группы».
 *
 * ОТРИЦАТЕЛЬНЫЙ НАМЕРЕННО. Номера настоящих счетов выдаёт база, и они всегда
 * положительные. Отрицательный номер не может совпасть ни с одним из них ни
 * сегодня, ни через десять лет. Взять «0» или «999999» значило бы однажды
 * столкнуться с настоящим счётом и молча сложить два разных остатка в один.
 */
export const INTERCOMPANY_SETTLEMENT_ACCOUNT_ID = -1;

/** Ключ названия строки в словарях сервера. */
export const INTERCOMPANY_SETTLEMENT_NAME = 'balance_sheet.intercompany_settlement';

/**
 * Нужна ли отчёту строка расчётов внутри группы.
 *
 * Нужна ТОЛЬКО когда отчёт сужен до части юрлиц. В режиме «все юрлица» обе
 * ноги любого внутреннего перевода уже внутри отчёта, перекоса нет, и строка
 * вышла бы нулевой.
 *
 * И это не только про лишнюю пустую строку. Пока строки нет, несходящийся
 * СВОДНЫЙ баланс остаётся виден — а он означает настоящую поломку в данных.
 * Строка, подставляемая всегда, заклеила бы этот сигнал наглухо.
 */
export function needsSettlementLine(
  legalEntityIds?: number[] | null,
): boolean {
  return (legalEntityIds ?? []).length > 0;
}

/** Итог проводок отчёта: сколько всего дебета и кредита он видит. */
export interface ScopeNet {
  debit: number;
  credit: number;
}

/**
 * Проводка вычисляемого счёта по перекосу отбора.
 *
 * Счёт дебетовый (это имущество), поэтому его остаток считается как
 * «дебет минус кредит». Чтобы остаток вышел равен МИНУС перекосу, дебет и
 * кредит меняются местами. Никаких отрицательных чисел в самой проводке при
 * этом не появляется — знак получается сам.
 *
 * Отдали своим — остаток положительный: «нам должны». Получили — отрицательный:
 * «мы должны». Обе стороны группы в сумме дают ноль, как и положено.
 */
export function settlementEntry(net: ScopeNet): {
  debit: number;
  credit: number;
} {
  return {
    debit: Number(net.credit) || 0,
    credit: Number(net.debit) || 0,
  };
}

/** Остаток строки: положительный — нам должны, отрицательный — мы должны. */
export function settlementBalance(net: ScopeNet): number {
  const entry = settlementEntry(net);

  return entry.debit - entry.credit;
}
