/**
 * Свойства ячейки таблицы.
 *
 * ЗАЧЕМ ОБЩИЙ ТИП. Движок таблицы передаёт КАЖДОЙ ячейке одну и ту же тройку:
 * колонку, строку и «посылку» — общие данные и обработчики таблицы. Каждый
 * компонент-ячейка расписывал её заново или не расписывал вовсе, и тогда
 * проверка типов не знала о ячейке ничего.
 *
 * Отсюда и бралась половина слепой зоны витрины: десятки ячеек, каждая со
 * своим безымянным набором свойств.
 *
 * `TRow` — что лежит в строке, `TPayload` — что таблица передала ячейке.
 * Оба по умолчанию свободные: у разных таблиц они разные, и сужать их надо
 * в самой ячейке, когда там и правда известно, с чем она работает.
 */
export interface DataTableCellProps<TRow = any, TPayload = any> {
  column: {
    /** Имя поля, которое правит эта ячейка. */
    id: string;
    /**
     * Колонка несёт и то, что положил её автор: подписи, настройки
     * переключателя, признак «выключено». Перечислять это здесь нельзя —
     * у каждой таблицы своё, — но и делать вид, что его нет, тоже.
     */
    [key: string]: any;
  };
  row: {
    /** Номер строки в таблице — по нему обновляют данные. */
    index: number;
    /** Сама строка. */
    original?: TRow;
    /**
     * Движок кладёт в строку и своё служебное — перечислять всё здесь
     * незачем, но и делать вид, что его нет, нельзя.
     */
    [key: string]: any;
  };
  /**
   * Значение самой ячейки.
   *
   * Движок передаёт его всегда; необязательным было БЫ удобно объявить, но
   * тогда ячейки, которые его и правда читают, пришлось бы обвешивать
   * проверками на пустоту, которых в жизни не бывает.
   */
  cell: {
    value?: any;
  };
  /** Общие данные и обработчики таблицы. */
  payload: TPayload;
}

/**
 * Посылка ячейки, которая правит значение в строке.
 *
 * Собрана из того, что такие ячейки и правда читают: обработчик записи и
 * ошибки по строкам.
 */
export interface EditableCellPayload {
  updateData: (index: number, columnId: string, value: unknown) => void;
  errors?: Array<Record<string, unknown>> | Record<string, unknown>;
}
