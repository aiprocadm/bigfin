import { describe, expect, it } from 'vitest';

import { initials } from './initials';

/**
 * UI-042-3 ТЗ-4. НАЙДЕНО ЖИВЫМ ПРОХОДОМ: у клиента «ООО «Настоящее»» в
 * значке стояло «О«» — первые символы двух первых слов, то есть буква формы
 * и кавычка. У российских названий первое слово почти всегда правовая форма,
 * и значки всех ООО выходили одинаковыми.
 */
describe('initials', () => {
  it.each([
    ['ООО «Настоящее»', 'Н'],
    ['ООО «Кривые реквизиты»', 'КР'],
    ['ИП Петров', 'П'],
    ['ИП Петров Иван Сергеевич', 'ПИ'],
    ['АО "Альфа-Банк"', 'А'],
    ['ПАО «Сбербанк России»', 'СР'],
    ['Иван Петров', 'ИП'],
    ['Ромашка', 'Р'],
    ['  демо   организация ', 'ДО'],
    ['Acme LLC', 'A'],
  ])('%s → %s', (name, expected) => {
    expect(initials(name)).toBe(expected);
  });

  it('название из одной формы — первая буква формы, а не пусто', () => {
    expect(initials('ООО')).toBe('О');
  });

  it('пустое и одни кавычки — пусто', () => {
    expect(initials('')).toBe('');
    expect(initials('«»')).toBe('');
  });
});
