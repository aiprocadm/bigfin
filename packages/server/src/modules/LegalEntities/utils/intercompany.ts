/**
 * Внутригрупповые обороты (этап 7 ТЗ, §7.2).
 *
 * Это то, что отличает настоящую консолидацию от простого сложения. Если ООО
 * перевело ИП 500 000 ₽, у группы не появилось ни дохода, ни расхода — деньги
 * остались внутри. Не исключить такие обороты значит завысить и выручку,
 * и расходы.
 *
 * Здесь только правила, без базы: ошибиться тут можно в обе стороны, и обе
 * ошибки молчаливые.
 */

/** Одна нога операции: на каком счёте и какому юрлицу он принадлежит. */
export interface TransactionLeg {
  accountId: number;
  /** null — юрлицо у счёта не проставлено. */
  legalEntityId?: number | null;
}

/**
 * Внутригрупповой ли перевод между двумя счетами.
 *
 * **Неизвестное юрлицо не считается «другим».** Колонка юрлица заполняется
 * отдельной задачей, и до неё у счетов стоит пусто. Если трактовать пустоту
 * как «другое юрлицо», внутригрупповым окажется КАЖДЫЙ перевод, и
 * консолидированный отчёт молча потеряет настоящую выручку.
 *
 * Ошибка в другую сторону (не исключили то, что стоило) заметна: оборот
 * останется в отчёте, и его покажет отдельный отчёт «Внутригрупповые
 * обороты». Поэтому при незнании выбираем её.
 */
export function isIntercompanyTransfer(
  fromLegalEntityId?: number | null,
  toLegalEntityId?: number | null,
): boolean {
  if (fromLegalEntityId == null || toLegalEntityId == null) return false;
  return Number(fromLegalEntityId) !== Number(toLegalEntityId);
}

/**
 * Внутригрупповая ли операция целиком — по её ногам.
 *
 * Операция внутригрупповая, когда её ноги принадлежат разным юрлицам и все
 * юрлица известны. Одна нога (или ноль) внутригрупповой быть не может:
 * перемещения между юрлицами не произошло.
 */
export function isIntercompanyReference(legs: TransactionLeg[]): boolean {
  const known = (legs ?? [])
    .map((leg) => leg.legalEntityId)
    .filter((id) => id != null)
    .map(Number);

  // Хоть одна нога без юрлица — не знаем, а значит не исключаем.
  if (known.length !== (legs ?? []).length) return false;
  if (known.length < 2) return false;

  return new Set(known).size > 1;
}

/**
 * Считать ли внутригрупповые обороты в этом отчёте.
 *
 * В режиме «все юрлица» они исключаются: для группы это перекладывание из
 * кармана в карман. В режиме одного юрлица — показываются, потому что для
 * НЕГО это настоящий доход или расход (§7.2 п. 3–4).
 *
 * Тонкость: произвольный набор из нескольких юрлиц — тоже консолидация,
 * просто по части группы. Обороты внутри выбранного набора исключаются.
 */
export function shouldExcludeIntercompany(
  legalEntityIds?: number[] | null,
): boolean {
  const selected = legalEntityIds ?? [];
  // Пусто = все юрлица (так договорились в §7.1) — это консолидация.
  if (selected.length === 0) return true;
  return selected.length > 1;
}
