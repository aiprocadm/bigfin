import { SetMetadata } from '@nestjs/common';

export const REQUIRE_OWNER_KEY = 'requireOrganizationOwner';

/**
 * Помечает контроллер (или отдельную ручку) как доступный только владельцу
 * организации: любому другому участнику ответом будет 403.
 *
 * Зачем это нужно. Права участников описываются ролями, но сами роли и список
 * участников — это уже не «данные», а границы доступа. Живая проба на стенде
 * показала, к чему приводит их незащищённость: пользователь с ролью
 * «Сотрудник», которой дано ровно шесть видов документов, спокойно создал
 * роль с правами на счета, настройки и блокировку периода. То есть вся система
 * разграничения обходилась в один запрос.
 *
 * Владелец определяется членством в организации (`user_tenants.role`), а не
 * ролью внутри организации: роль можно переписать изнутри, членство — нет.
 *
 * @example
 * ```typescript
 * @Controller('roles')
 * @UseGuards(OwnerGuard)
 * @RequireOwner()
 * export class RolesController { ... }
 * ```
 */
export const RequireOwner = () => SetMetadata(REQUIRE_OWNER_KEY, true);
