/**
 * Валюта группы (этап 7 ТЗ, §7.4, остаток К4).
 *
 * ЧТО ГОВОРИТ ТЗ. «Если у юрлиц разные базовые валюты, консолидация ведётся в
 * валюте группы (настройка организации) по курсу на дату операции.» Курс,
 * значит, назван прямо в ТЗ — выбирать между «на дату операции», «на дату
 * отчёта» и «по среднему» не требуется.
 *
 * ЧТО УЖЕ БЫЛО. Продукт так и считает, причём с самого начала: дебет и кредит
 * проводки хранятся В ВАЛЮТЕ ГРУППЫ, пересчитанные по курсу на дату операции;
 * исходная сумма и курс лежат рядом отдельными полями. Поэтому сложить юрлица
 * с разными валютами можно прямо, ничего не пересчитывая при построении
 * отчёта. Это ХОРОШО: пересчёт на лету означал бы, что вчерашний отчёт
 * сегодня показывает другие числа.
 *
 * ЧЕГО НЕ БЫЛО. Человек не видел, в какой валюте перед ним числа. Пока юрлицо
 * одно и валюта одна — вопрос не возникает. Как только в группе появляется
 * юрлицо с другой валютой, сводная цифра становится непонятной: рубли это,
 * тенге или сумма несложимого.
 */

/** Юрлицо с точки зрения валюты: больше про него ничего не нужно. */
export interface EntityCurrency {
  baseCurrency?: string | null;
}

export interface GroupCurrencyMeta {
  /** Валюта, в которой построен отчёт (настройка организации). */
  groupCurrency: string;
  /** Есть ли в группе юрлицо с ДРУГОЙ валютой учёта. */
  isMultiCurrency: boolean;
  /** Все валюты группы, по одному разу, в порядке появления. */
  currencies: string[];
}

/**
 * Что сказать про валюту в шапке отчёта.
 *
 * Пустая валюта юрлица — это «как у группы», а не «неизвестно». Колонка
 * появилась позже самих юрлиц, и у заведённых раньше она пуста. Считать пустое
 * за другую валюту значило бы объявить многовалютной каждую вторую группу.
 */
export function describeGroupCurrency(
  groupCurrency: string,
  entities: EntityCurrency[] | null | undefined,
): GroupCurrencyMeta {
  const base = String(groupCurrency || '').toUpperCase();
  const currencies: string[] = base ? [base] : [];

  (entities ?? []).forEach((entity) => {
    const code = String(entity?.baseCurrency || '').toUpperCase();

    if (!code) return;
    if (currencies.includes(code)) return;

    currencies.push(code);
  });

  return {
    groupCurrency: base,
    isMultiCurrency: currencies.length > 1,
    currencies,
  };
}
