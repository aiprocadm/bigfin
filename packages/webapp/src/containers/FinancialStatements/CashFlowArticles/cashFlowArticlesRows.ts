/**
 * Строки отчёта «Деньги (ДДС по статьям)»: какие из них итоговые (FIN-013).
 *
 * Раскрытие и уплощение дерева с этапа 30 делает общая таблица отчётов
 * (`ui/report-table`): у матрицы «статьи × периоды» те же строки, что у
 * остальных отчётов, и держать для неё вторую таблицу значило бы чинить
 * одно и то же дважды. Здесь остался только признак итоговой строки.
 */

/** Строки-итоги: выделяются начертанием и чертой сверху. */
export const TOTAL_ROW_TYPES = [
  'OPENING',
  'CLOSING',
  'NET',
  'UNCLASSIFIED',
] as const;

/** Итоговая ли это строка — её показывают жирным. */
export const isTotalRow = (rowType: string): boolean =>
  (TOTAL_ROW_TYPES as readonly string[]).includes(rowType);
