import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';

/**
 * О3 карты v23. Цели нажатия дотягиваются до пальца.
 *
 * Палец накрывает примерно сантиметр — это около 44 px, и таков
 * общепринятый минимум для касания. Меню продукта размечено `py-2`, то есть
 * 36 px: на мыши это удобно, а на телефоне пункты идут вплотную, и промах
 * уводит в соседний раздел.
 *
 * Правило простое: у пункта меню должна быть заявлена минимальная высота
 * для узких экранов. На больших экранах прежние 36 px остаются — там
 * указатель точный, и лишняя высота съедала бы список.
 */
const SIDEBAR = path.resolve(__dirname, 'Sidebar.tsx');

describe('цели нажатия', () => {
  const source = fs.readFileSync(SIDEBAR, 'utf8');

  it('файл меню читается', () => {
    // Иначе проверка ниже стала бы пустой и зелёной.
    expect(source).toContain('aria-current');
  });

  it('пункт меню задаёт минимальную высоту для телефона', () => {
    // `min-h-11` — это 44px в шкале Tailwind (11 × 4px).
    expect(source).toMatch(/min-h-11/);
  });

  it('на больших экранах высота остаётся прежней', () => {
    // Ограничение снимается с определённой ширины: иначе список разделов
    // на десктопе стал бы вдвое длиннее без всякой пользы.
    expect(source).toMatch(/(sm|md|lg):min-h-0/);
  });
});
