/**
 * Валидация КПП (Код причины постановки на учёт).
 * 9 символов. Позиции 1-4 — код налогового органа (цифры).
 * Позиции 5-6 — код причины: либо обе цифры (для российских организаций),
 *                либо обе латинские буквы A-Z (для иностранных); смесь
 *                цифры+буквы не допускается.
 * Позиции 7-9 — порядковый номер (цифры).
 */
export function isValidKpp(value: string): boolean {
  if (typeof value !== 'string') return false;
  return /^[0-9]{4}([0-9]{2}|[A-Z]{2})[0-9]{3}$/.test(value);
}
