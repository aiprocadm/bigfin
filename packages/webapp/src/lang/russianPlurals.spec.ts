import fs from 'fs';
import path from 'path';
import { describe, expect, it } from 'vitest';
import intl from 'react-intl-universal';

/**
 * Числа и слова рядом с ними согласованы по-русски.
 *
 * НАЙДЕНО ЖИВЫМ ПРОХОДОМ. На главной висело «3 операций ждут разноски».
 * По-русски правильно «3 операции ждут», и разница заметна любому носителю
 * языка: строка сразу читается как машинный перевод.
 *
 * По-русски форма зависит от числа ТРОЯКО: 1 операция, 2–4 операции,
 * 5–20 операций. Английскому хватает двух форм, поэтому строка, написанная
 * «как в английском», в русском всегда будет хромать в двух случаях из трёх.
 *
 * Тест этого не видел и не мог: строка есть, число подставлено, ошибок нет.
 */
const RU = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'ru/index.json'), 'utf8'),
) as Record<string, string>;

/**
 * Существительные, которые СКЛОНЯЮТСЯ и потому не могут стоять сразу после
 * числа в неизменном виде.
 *
 * Не весь словарь: только то, что реально считают в продукте. Список можно
 * дополнять — он и есть правило.
 */
const COUNTABLE = [
  'операций',
  'операции',
  'счетов',
  'счёта',
  'документов',
  'документа',
  'контрагентов',
  'контрагента',
  'записей',
  'записи',
  'дней',
  'дня',
];

describe('русские склонения после числа', () => {
  it('словарь прочитан', () => {
    expect(Object.keys(RU).length).toBeGreaterThan(1000);
  });

  it('после числа не стоит застывшее существительное', () => {
    const offenders = Object.entries(RU)
      // Не все значения словаря — строки: часть ключей хранит вложенные
      // наборы. Без этой проверки спека падает на собственной ошибке, а не
      // на находке.
      .filter(([, value]) => typeof value === 'string')
      .filter(([, value]) => !value.includes('plural'))
      .filter(([, value]) =>
        COUNTABLE.some((word) =>
          // БЕЗ `\b`. Граница слова в регулярных выражениях определена через
          // латиницу: после «операций» стоит пробел, но ни «й», ни пробел не
          // считаются «буквой», перехода нет — и правило молча не срабатывало.
          // Найдено мутацией: вернул застывшее «операций», сторож не заметил.
          new RegExp(`\\{\\w+\\}\\s+${word}(?![а-яё])`, 'i').test(value),
        ),
      )
      .map(([key, value]) => `${key}: ${value}`);

    expect(offenders).toEqual([]);
  });

  it('правило склонения и правда работает', () => {
    // Проверка САМОГО правила, а не только его записи: иначе сторож защищал
    // бы строку, которая склоняет неправильно.
    // Проверка идёт ЧЕРЕЗ ТУ ЖЕ библиотеку, что и продукт. Своя
    // реализация правила проверяла бы себя саму, а не то, что увидит
    // человек.
    intl.init({ currentLocale: 'ru', locales: { ru: RU } });

    const say = (count: number) =>
      intl.get('dashboard.attention.uncategorized', { count });

    expect(say(1)).toContain('1 операция ждёт');
    expect(say(3)).toContain('3 операции ждут');
    expect(say(5)).toContain('5 операций ждут');
    // Одиннадцать — ловушка: кончается на «один», а форма как у пяти.
    expect(say(11)).toContain('11 операций ждут');
    // Двадцать один — наоборот: форма как у одного.
    expect(say(21)).toContain('21 операция ждёт');
  });
});
