/**
 * Название валюты на языке организации.
 * @param {string} currencyCode - Код валюты (`RUB`, `USD`…).
 * @param {string} lang - Язык организации (`ru` | `en` | …).
 * @returns {string} Название валюты; для неизвестного кода — сам код.
 */
export const currencyName = (currencyCode: string, lang = 'en'): string => {
  const meta = Currencies[currencyCode];

  if (lang === 'ru') {
    const russian = RUSSIAN_CURRENCY_NAMES[currencyCode];

    if (russian) return russian;
  }
  // Неизвестный библиотеке код всё равно должен дать читаемое имя:
  // пустое название валюты в списке выглядит как поломка.
  return meta?.name ?? currencyCode;
};
