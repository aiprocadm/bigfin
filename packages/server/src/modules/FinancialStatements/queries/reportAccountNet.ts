/**
 * Вклад счёта в сумму отчёта — одно правило на весь раздел отчётов.
 *
 * У счетов с нормальной стороной «кредит» (доходы, обязательства) это
 * кредит минус дебет, у остальных — наоборот. Складывать «как есть» нельзя:
 * половина строк уйдёт с обратным знаком.
 *
 * Правило вынесено в отдельный файл намеренно. Им пользуются и раскрытие
 * суммы до операций, и колонка «Отклонение» план-факта. Две копии правила
 * рано или поздно разойдутся, и рядом окажутся два числа, каждое из которых
 * выглядит правдоподобно, — худший вид ошибки в учёте.
 */

/**
 * Нормальная сторона счёта. Поле называется по-разному в разных местах
 * ответа модели, поэтому принимаем оба написания — иначе половина счетов
 * молча посчиталась бы с обратным знаком.
 */
export function isCreditNormalAccount(account: any): boolean {
  const normal = account?.accountNormal ?? account?.account_normal;
  return normal === 'credit';
}

/** Вклад одной проводки (или их суммы) в число отчёта. */
export function reportAccountNet(
  debit: number | string | null | undefined,
  credit: number | string | null | undefined,
  isCreditNormal: boolean,
): number {
  const d = Number(debit ?? 0);
  const c = Number(credit ?? 0);
  return isCreditNormal ? c - d : d - c;
}
