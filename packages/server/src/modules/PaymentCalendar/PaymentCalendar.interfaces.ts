/** Одна строка-источник внутри дня. */
export interface ForecastLine {
  direction: 'inflow' | 'outflow';
  amount: number; // в базовой валюте
  label: string;
  source: 'invoice' | 'bill' | 'manual' | 'recurring';
  // Только у плановых строк — для кнопки «Записать в учёт» (О3 карты v13).
  plannedOperationId?: number;
}

/** Чистые суммы за день (вход для бегущего остатка). */
export interface DayFlow {
  date: string; // YYYY-MM-DD
  inflow: number;
  outflow: number;
}

/** День с посчитанным остатком на конец. */
export interface DayBalance extends DayFlow {
  balance: number;
  lines?: ForecastLine[];
}

/** Кассовый разрыв. */
export interface CashGap {
  date: string;
  amount: number; // положительное число = размер дефицита
  daysFromStart: number;
}

/**
 * Интервал кассового разрыва: сплошная полоса дней, когда остаток ниже нуля.
 *
 * ЗАЧЕМ ИНТЕРВАЛ, А НЕ ОДИН ДЕНЬ. Разрыв — это не точка, а яма: у неё есть
 * начало, дно и край, из-за которого выбираются. Пока наружу отдавался только
 * первый день, ответить на вопрос «сколько денег и к какому числу нужно
 * занять» было нечем: занимать надо на глубину ямы, а не на её первый день,
 * и вернуть можно не раньше, чем она кончится.
 *
 * ЗАЧЕМ СПИСОК, А НЕ ОДНА ЯМА. Ям в горизонте бывает несколько. Первая может
 * быть мелкой и короткой, а вторая — той, ради которой и стоит шевелиться.
 * Показав только первую, продукт отвечал бы на вопрос, которого не задавали.
 */
export interface CashGapInterval {
  /** Первый день, когда остаток ушёл в минус. */
  from: string;
  /**
   * Последний день минуса. `null` означает, что разрыв НЕ ЗАКРЫЛСЯ до конца
   * горизонта — это не «данных нет», а самый тревожный из ответов, и путать
   * его с закрытым разрывом нельзя.
   */
  to: string | null;
  /** Самая большая нехватка внутри интервала, положительное число. */
  deepestAmount: number;
  /** День самой большой нехватки — дно ямы. */
  deepestDate: string;
}

/** Результат расчёта остатка по дням. */
export interface ForecastResult {
  days: DayBalance[];
  /**
   * Первый разрыв. Остаётся ради тех, кто уже читает это поле: вердикт на
   * главной, оповещение о разрыве и плитка дашборда. Значение выводится из
   * `gaps[0]`, чтобы источник правды был один.
   */
  gap: CashGap | null;
  /** Все разрывы горизонта по порядку. */
  gaps: CashGapInterval[];
}

/** Полный ответ прогноза календаря. */
export interface PaymentCalendarResponse {
  baseCurrency: string;
  /**
   * Сколько строк не удалось пересчитать в базовую валюту: у документа в
   * валюте не записан курс. Молча считать их один к одному нельзя —
   * прогноз завышался (Р1 карты v16).
   */
  unconvertedCount: number;
  openingBalance: number;
  fromDate: string;
  toDate: string;
  days: DayBalance[];
  /**
   * Столбцы выбранного масштаба (FIN-019 ТЗ-2). Дни остаются рядом: на них
   * держатся лента денег на главной, оповещение о разрыве и виджет шапки.
   */
  periods?: unknown[];
  granularity?: string;
  source?: string;
  gap: CashGap | null;
  gaps: CashGapInterval[];
}
