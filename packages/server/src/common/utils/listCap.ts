/**
 * С1 карты v49. Потолок выдачи списка.
 *
 * Замер: из 35 списочных запросов ограничение выдачи есть у шести.
 * Остальные отдают всё, что накопилось в базе, а витрина рисует это одним
 * куском. Пока записей десятки — незаметно; на растущем реестре заявок
 * (заявку заводят на каждый платёж) это долгая загрузка и подвисший
 * телефон, а основатель работает с продуктом с телефона.
 *
 * Приём взят у сводки недоставленных писем (`GetFailedMails`): запросить на
 * одну строку больше потолка. Пришло больше — значит есть ещё, и об этом
 * надо сказать человеку, а не молча обрезать список.
 *
 * Почему потолок, а не постраничный обход: у этих разделов уже есть поиск
 * (карты v43 и v48) — это и есть способ сузить выдачу. Постраничный обход
 * стоил бы правки каждого экрана, а молчаливую потерю строк закрывает уже
 * сам потолок.
 */
export const LIST_CAP = 200;

/** Минимум, который нужен помощнику от строителя запроса. */
interface CappableBuilder {
  limit(count: number): unknown;
}

/**
 * Просит на одну строку больше потолка: лишняя не показывается, но по ней
 * видно, что список обрезан.
 */
export function applyListCap(builder: CappableBuilder, cap = LIST_CAP): void {
  builder.limit(cap + 1);
}

/** Делит ответ на показываемое и признак «есть ещё». */
export function splitCapped<T>(
  rows: T[],
  cap = LIST_CAP,
): { items: T[]; truncated: boolean } {
  const truncated = rows.length > cap;

  return { items: truncated ? rows.slice(0, cap) : rows, truncated };
}
